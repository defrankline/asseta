/**
 * Runtime (Yup) response schemas for petty cash funds (DEC-033). Money values are decimal strings
 * and stay strings; schemas are annotated with the generated contract types.
 */
import { array, object, type Schema } from 'yup';
import type {
  AdvanceStatus,
  CountReason,
  FundFigure,
  HolderChangeStatus,
  MovementKind,
  MovementStatus,
  PettyCashAdjustmentDto,
  PettyCashAdvanceDto,
  PettyCashBalanceDto,
  PettyCashCountDto,
  PettyCashFundDto,
  PettyCashHolderChangeDto,
  PettyCashMovementDto,
  PettyCashStatementDto,
  PettyCashStatementLineDto,
  PettyCashTransactionDto,
  TopUpExpenseDto,
  TopUpSuggestionDto,
} from '../pettyCashTypes';
import { ACK_METHODS, DECISION_STATUSES } from './custodySchemas';
import {
  bool,
  id,
  idList,
  int,
  nullableId,
  nullableOneOf,
  nullableText,
  oneOf,
  text,
} from './schemaKit';

export const FUND_FIGURES: readonly FundFigure[] = [
  'funded',
  'spent',
  'returned',
  'adjustments',
  'written_off',
  'advances_issued',
  'advance_change_returned',
  'pending_spending',
  'awaiting_acknowledgement',
  'returns_claimed',
  'open_return_differences',
  'pending_adjustments',
  'advances_outstanding',
  'advance_spending',
];
export const MOVEMENT_KINDS: readonly MovementKind[] = ['FUNDING', 'TOP_UP', 'RETURN'];
export const MOVEMENT_STATUSES: readonly MovementStatus[] = [
  'PROPOSED',
  'APPROVED',
  'REJECTED',
  'ISSUED',
  'ACKNOWLEDGED',
  'DISPUTED',
  'CLAIMED',
  'CONFIRMED',
];
export const COUNT_REASONS: readonly CountReason[] = ['ROUTINE', 'HOLDER_CHANGE'];
export const HOLDER_CHANGE_STATUSES: readonly HolderChangeStatus[] = [
  'PENDING',
  'ACKNOWLEDGED',
  'DECLINED',
  'CANCELLED',
];
export const ADVANCE_STATUSES: readonly AdvanceStatus[] = ['OUTSTANDING', 'CLEARED'];

/** Optional server-filled display name (`*_name`, filled by `named`). */
const name = () => nullableText().default(null);

const balanceObject = object({
  fund_id: id(),
  fund_code: text(),
  fund_name: text(),
  currency: text(),
  holder_staff_id: id(),
  holder_staff_name: name(),
  is_active: bool(),
  approved_limit: text(),
  low_balance_level: nullableText(),
  balance: text(),
  available_to_spend: text(),
  below_low_balance: bool(),
  funded: text(),
  spent: text(),
  returned: text(),
  adjustments: text(),
  written_off: text(),
  advances_issued: text(),
  advance_change_returned: text(),
  pending_spending: text(),
  awaiting_acknowledgement: text(),
  returns_claimed: text(),
  open_return_differences: text(),
  pending_adjustments: text(),
  advances_outstanding: text(),
  advance_spending: text(),
  last_count_at: nullableText().default(null),
  next_count_due_at: nullableText().default(null),
  as_of: text(),
});

export const balanceSchema: Schema<PettyCashBalanceDto> = balanceObject;

export const fundSchema: Schema<PettyCashFundDto> = object({
  id: id(),
  code: text(),
  name: text(),
  holder_staff_id: id(),
  holder_staff_name: name(),
  job_site_id: nullableId(),
  job_site_name: name(),
  currency: text(),
  approved_limit: text(),
  low_balance_level: nullableText(),
  note: nullableText(),
  is_active: bool(),
  version: int(),
  created_by: nullableId(),
  created_by_name: name(),
  created_at: text(),
  deactivated_at: nullableText(),
  deactivated_by: nullableId(),
  deactivated_by_name: name(),
  deactivation_reason: nullableText(),
  pending_holder_change_id: nullableId().default(null),
  balance: balanceObject.nullable().default(null),
});

export const transactionSchema: Schema<PettyCashTransactionDto> = object({
  figure: oneOf(FUND_FIGURES),
  occurred_at: text(),
  amount: text(),
  currency: text(),
  entity_type: text(),
  entity_id: id(),
  status: text(),
  reference: nullableText(),
  note: nullableText(),
  recorded_by: nullableId(),
  recorded_by_name: name(),
});

const statementLineSchema: Schema<PettyCashStatementLineDto> = object({
  occurred_at: text(),
  figure: oneOf(FUND_FIGURES),
  entity_type: text(),
  entity_id: id(),
  reference: nullableText(),
  note: nullableText(),
  money_in: text(),
  money_out: text(),
  running_balance: text(),
});

export const statementSchema: Schema<PettyCashStatementDto> = object({
  fund_id: id(),
  currency: text(),
  timezone: text(),
  date_from: text(),
  date_to: text(),
  opening_balance: text(),
  closing_balance: text(),
  lines: array(statementLineSchema).required(),
});

export const topUpExpenseSchema: Schema<TopUpExpenseDto> = object({
  id: id(),
  description: text(),
  amount: text(),
  incurred_at: text(),
  decided_at: nullableText(),
  category_id: id(),
  machine_id: nullableId(),
  job_id: nullableId(),
});

export const suggestionSchema: Schema<TopUpSuggestionDto> = object({
  fund_id: id(),
  currency: text(),
  balance: text(),
  approved_limit: text(),
  in_flight: text(),
  cap: text(),
  since: nullableText(),
  spending_since: text(),
  suggested: text(),
  expenses: array(topUpExpenseSchema).required(),
});

export const movementSchema: Schema<PettyCashMovementDto> = object({
  id: id(),
  number: text(),
  fund_id: id(),
  petty_cash_fund_name: name(),
  kind: oneOf(MOVEMENT_KINDS),
  status: oneOf(MOVEMENT_STATUSES),
  client_id: nullableId(),
  holder_staff_id: id(),
  holder_staff_name: name(),
  amount: text(),
  currency: text(),
  deposit_account_id: nullableId(),
  deposit_account_name: name(),
  method: nullableText(),
  reference: nullableText(),
  note: nullableText(),
  suggested_amount: nullableText(),
  cap_amount: nullableText(),
  above_cap_reason: nullableText(),
  basis_from: nullableText(),
  evidence_attachment_ids: idList(),
  source: text(),
  created_by: nullableId(),
  created_by_name: name(),
  created_at: text(),
  client_created_at: nullableText(),
  decided_by: nullableId(),
  decided_by_name: name(),
  decided_at: nullableText(),
  decision_note: nullableText(),
  issued_by: nullableId(),
  issued_by_name: name(),
  issued_at: nullableText(),
  received_by: nullableId(),
  received_by_name: name(),
  received_at: nullableText(),
  amount_received: nullableText(),
  receipt_method: nullableOneOf(ACK_METHODS),
  receipt_note: nullableText(),
  variance_id: nullableId().default(null),
});

export const countSchema: Schema<PettyCashCountDto> = object({
  id: id(),
  number: text(),
  fund_id: id(),
  petty_cash_fund_name: name(),
  client_id: nullableId(),
  reason: oneOf(COUNT_REASONS),
  holder_staff_id: id(),
  holder_staff_name: name(),
  currency: text(),
  counted_amount: text(),
  expected_amount: text(),
  difference: text(),
  counted_by: nullableId(),
  counted_by_name: name(),
  counted_at: text(),
  witness_user_id: nullableId(),
  witness_user_name: name(),
  self_count: bool(),
  evidence_attachment_ids: idList(),
  note: nullableText(),
  source: text(),
  policy_version: nullableText(),
  client_created_at: nullableText(),
  variance_id: nullableId().default(null),
});

export const holderChangeSchema: Schema<PettyCashHolderChangeDto> = object({
  id: id(),
  fund_id: id(),
  petty_cash_fund_name: name(),
  from_staff_id: id(),
  from_staff_name: name(),
  to_staff_id: id(),
  to_staff_name: name(),
  count_id: id(),
  status: oneOf(HOLDER_CHANGE_STATUSES),
  note: nullableText(),
  requested_by: nullableId(),
  requested_by_name: name(),
  requested_at: text(),
  decided_by: nullableId(),
  decided_by_name: name(),
  decided_at: nullableText(),
  decision_note: nullableText(),
});

export const adjustmentSchema: Schema<PettyCashAdjustmentDto> = object({
  id: id(),
  number: text(),
  fund_id: id(),
  petty_cash_fund_name: name(),
  amount: text(),
  currency: text(),
  reason_id: nullableId(),
  reason: text(),
  evidence_attachment_ids: idList(),
  status: oneOf(DECISION_STATUSES),
  created_by: nullableId(),
  created_by_name: name(),
  created_at: text(),
  decided_by: nullableId(),
  decided_by_name: name(),
  decided_at: nullableText(),
  decision_note: nullableText(),
});

export const advanceSchema: Schema<PettyCashAdvanceDto> = object({
  id: id(),
  number: text(),
  fund_id: id(),
  petty_cash_fund_name: name(),
  client_id: nullableId(),
  recipient_staff_id: id(),
  recipient_staff_name: name(),
  amount: text(),
  currency: text(),
  purpose: text(),
  status: oneOf(ADVANCE_STATUSES),
  issued_by: nullableId(),
  issued_by_name: name(),
  issued_at: text(),
  due_at: text(),
  overdue: bool(),
  source: text(),
  client_created_at: nullableText(),
  cleared_by: nullableId(),
  cleared_by_name: name(),
  cleared_at: nullableText(),
  spent_amount: nullableText(),
  change_returned: nullableText(),
  clear_note: nullableText(),
  approved_spending: text(),
  pending_spending: text(),
  remaining: text(),
  variance_id: nullableId().default(null),
});
