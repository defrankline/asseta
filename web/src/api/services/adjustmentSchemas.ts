import { object, string, type Schema } from 'yup';
import type {
  AdjustmentEntryDto,
  AdjustmentEntryStatus,
  AdjustmentRequestDto,
  AdjustmentRequestStatus,
  AdjustmentRequestType,
  AdjustmentType,
  AdjustmentUnit,
  RefundSettlement,
} from '../adjustmentTypes';
import {
  id,
  idList,
  nullableId,
  nullableOneOf,
  nullableText,
  oneOf,
  record,
  text,
} from './schemaKit';

export const ADJUSTMENT_TYPES: readonly AdjustmentType[] = [
  'HOURS_TRANSFER',
  'HOURS_CANCELLATION',
  'HOURS_CORRECTION',
  'HOURS_REFUND',
  'CREDIT_ARRANGEMENT',
  'METER_CORRECTION',
  'ALLOCATION_CORRECTION',
  'ENGINE_HOUR_CLASSIFICATION',
  'NON_REVENUE_APPROVAL',
  'CASH_WRITE_OFF',
  'CASH_VARIANCE_RESOLUTION',
  'CUSTODY_ADJUSTMENT',
  'INVOICE_VOID',
  'PAYMENT_REVERSAL',
  'COLLECTION_REVERSAL',
  'PURCHASE_REVERSAL',
];
export const ADJUSTMENT_UNITS: readonly AdjustmentUnit[] = ['HOURS', 'MONEY', 'READING'];
export const ENTRY_STATUSES: readonly AdjustmentEntryStatus[] = ['APPROVED', 'REJECTED', 'REVOKED'];
export const REQUEST_TYPES: readonly AdjustmentRequestType[] = [
  'HOURS_CORRECTION',
  'HOURS_REFUND',
  'PAYMENT_REVERSAL',
  'COLLECTION_REVERSAL',
  'PURCHASE_REVERSAL',
  'INVOICE_VOID',
];
export const REQUEST_STATUSES: readonly AdjustmentRequestStatus[] = [
  'PROPOSED',
  'APPROVED',
  'REJECTED',
  'WITHDRAWN',
];
export const SETTLEMENTS: readonly RefundSettlement[] = ['CREDIT', 'PAY_OUT'];

const optionalText = () => string().nullable().default(null);

export const adjustmentEntrySchema: Schema<AdjustmentEntryDto> = object({
  id: id(),
  adjustment_type: oneOf(ADJUSTMENT_TYPES),
  status: oneOf(ENTRY_STATUSES),
  unit: oneOf(ADJUSTMENT_UNITS),
  original_type: text(),
  original_id: id(),
  original_reference: nullableText(),
  source_type: text(),
  source_id: id(),
  original_value: nullableText(),
  new_value: nullableText(),
  amount: nullableText(),
  currency: nullableText(),
  resulting_balance: nullableText(),
  reason_id: nullableId(),
  reason_label: nullableText(),
  reason: nullableText(),
  evidence_attachment_ids: idList(),
  customer_id: nullableId(),
  customer_name: optionalText(),
  machine_id: nullableId(),
  machine_code: optionalText(),
  machine_name: optionalText(),
  staff_member_id: nullableId(),
  staff_member_name: optionalText(),
  requested_by: nullableId(),
  requested_by_name: optionalText(),
  requested_at: nullableText(),
  approved_by: nullableId(),
  approved_by_name: optionalText(),
  approved_at: nullableText(),
  decision_note: nullableText(),
  details: record(),
  posted_at: text(),
});

export const adjustmentRequestSchema: Schema<AdjustmentRequestDto> = object({
  id: id(),
  client_id: nullableId(),
  request_type: oneOf(REQUEST_TYPES),
  status: oneOf(REQUEST_STATUSES),
  original_type: text(),
  original_id: id(),
  original_reference: nullableText(),
  purchase_id: nullableId(),
  purchase_number: optionalText(),
  customer_id: nullableId(),
  customer_name: optionalText(),
  machine_id: nullableId(),
  machine_code: optionalText(),
  machine_name: optionalText(),
  hours: nullableText(),
  amount: nullableText(),
  currency: nullableText(),
  settlement: nullableOneOf(SETTLEMENTS),
  reason: text(),
  reason_code_id: nullableId(),
  reason_label: optionalText(),
  evidence_attachment_ids: idList(),
  params: record(),
  effects: record(),
  proposed_by: nullableId(),
  proposed_by_name: optionalText(),
  proposed_at: text(),
  decided_by: nullableId(),
  decided_by_name: optionalText(),
  decided_at: nullableText(),
  decision_note: nullableText(),
});
